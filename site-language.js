const defaultLanguage = 'en-US';
const selector = document.querySelector('#site-language');
const textFields = document.querySelectorAll('[data-text]');
const screenshots = document.querySelectorAll('#screenshot-gallery a');
const privacyLink = document.querySelector('#privacy-link');
const description = document.querySelector('meta[name="description"]');

function renderLanguage(language) {
  const copy = translations[language];
  document.documentElement.lang = language;
  document.title = `${copy.title} — Plyska Apps`;
  description.content = copy.intro;
  selector.value = language;

  for (const element of textFields) {
    element.textContent = copy[element.dataset.text];
  }
  privacyLink.href = copy.privacyPath;

  screenshots.forEach((link, index) => {
    const path = `/screenshots/${language}-${link.dataset.file}`;
    const image = link.querySelector('img');
    if (link.getAttribute('href') !== path) {
      link.href = path;
      image.src = path;
    }
    image.alt = copy.alt[index];
  });
}

function restoreLanguage() {
  const requested = new URL(location.href).searchParams.get('lang');
  renderLanguage(Object.hasOwn(translations, requested) ? requested : defaultLanguage);
}

selector.addEventListener('change', () => {
  const language = selector.value;
  const url = new URL(location.href);
  if (language === defaultLanguage) {
    url.searchParams.delete('lang');
  } else {
    url.searchParams.set('lang', language);
  }
  history.replaceState(null, '', url);
  renderLanguage(language);
});

window.addEventListener('popstate', restoreLanguage);
window.addEventListener('pageshow', restoreLanguage);
restoreLanguage();
selector.closest('.page-language').hidden = false;
